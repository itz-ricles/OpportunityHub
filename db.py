"""Database access: SQLite for local development, PostgreSQL (e.g. Amazon RDS) when DATABASE_URL is set.

Every other module talks to the small `Database` wrapper below, never to sqlite3 or psycopg directly,
so switching engines is a configuration change, not a rewrite."""
import sqlite3
from pathlib import Path

import click
from flask import current_app, g

try:
    import psycopg
except ImportError:  # SQLite-only installs work without the PostgreSQL driver
    psycopg = None

SCHEMA_PATH = Path(__file__).resolve().parent / "database" / "schema.sql"
DROP_ALL = """
DROP TABLE IF EXISTS applications;
DROP TABLE IF EXISTS saved_opportunities;
DROP TABLE IF EXISTS opportunities;
DROP TABLE IF EXISTS users;
"""

# Catch this to detect constraint violations (duplicates, bad foreign keys, CHECK failures) on either engine.
IntegrityErrors = (sqlite3.IntegrityError,) + ((psycopg.IntegrityError,) if psycopg else ())


class Row(dict):
    """PostgreSQL row that behaves like sqlite3.Row: row["name"], row[0] and dict(row) all work."""

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)


def _pg_row_factory(cursor):
    names = [column.name for column in cursor.description] if cursor.description else []
    return lambda values: Row(zip(names, values))


class Database:
    """Thin wrapper hiding the differences between SQLite and PostgreSQL."""

    def __init__(self, conn, backend):
        self.conn = conn
        self.backend = backend  # "sqlite" or "postgres"

    @property
    def like(self):
        """Case-insensitive LIKE operator (SQLite LIKE already ignores ASCII case; PostgreSQL needs ILIKE)."""
        return "ILIKE" if self.backend == "postgres" else "LIKE"

    def _sql(self, sql):
        if self.backend == "postgres":  # we write "?" placeholders everywhere; psycopg wants "%s"
            return sql.replace("%", "%%").replace("?", "%s")
        return sql

    def execute(self, sql, params=()):
        try:
            return self.conn.execute(self._sql(sql), params)
        except Exception:
            if self.backend == "postgres":
                self.conn.rollback()  # a failed statement poisons the whole PostgreSQL transaction
            raise

    def insert_returning_id(self, sql, params=()):
        """Run an INSERT and return the new row's id, or None if nothing was inserted (ON CONFLICT DO NOTHING)."""
        if self.backend == "postgres":
            row = self.execute(sql + " RETURNING id", params).fetchone()
            return row["id"] if row else None
        cursor = self.execute(sql, params)
        return cursor.lastrowid if cursor.rowcount == 1 else None

    def executescript(self, script):
        if self.backend == "postgres":
            self.conn.execute(script)
        else:
            self.conn.executescript(script)
        self.conn.commit()

    def commit(self):
        self.conn.commit()

    def close(self):
        self.conn.close()


def get_db():
    """One connection per request, stored on flask.g."""
    if "db" not in g:
        url = current_app.config.get("DATABASE_URL")
        if url:
            if psycopg is None:
                raise RuntimeError("DATABASE_URL is set but psycopg is missing. Run: pip install -r requirements.txt")
            conn = psycopg.connect(url, row_factory=_pg_row_factory, connect_timeout=5)
            g.db = Database(conn, "postgres")
        else:
            path = current_app.config["DATABASE_PATH"]
            Path(path).parent.mkdir(parents=True, exist_ok=True)
            conn = sqlite3.connect(path)
            conn.row_factory = sqlite3.Row
            conn.execute("PRAGMA foreign_keys = ON")  # SQLite ignores foreign keys unless asked
            g.db = Database(conn, "sqlite")
    return g.db


def close_db(_error=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def sqlite_schema():
    return SCHEMA_PATH.read_text(encoding="utf-8")


def postgres_schema():
    """Same schema file; only the auto-numbering syntax differs."""
    return sqlite_schema().replace(
        "INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")


def init_db(reset=False):
    db = get_db()
    if reset:
        db.executescript(DROP_ALL)
    db.executescript(postgres_schema() if db.backend == "postgres" else sqlite_schema())


def init_app(app):
    app.teardown_appcontext(close_db)

    @app.cli.command("init-db")
    def init_db_command():
        """Create the tables (safe to run twice)."""
        init_db()
        click.echo("Database initialised.")

    @app.cli.command("seed-db")
    def seed_db_command():
        """Insert demo opportunities (only if the table is empty)."""
        from seed import seed_opportunities
        click.echo(f"Seeded {seed_opportunities()} demo opportunities.")

    @app.cli.command("reset-db")
    @click.confirmation_option(prompt="This DELETES all data. Continue?")
    def reset_db_command():
        """Drop everything, recreate tables, reseed."""
        from seed import seed_opportunities
        init_db(reset=True)
        click.echo(f"Database reset. Seeded {seed_opportunities()} demo opportunities.")
