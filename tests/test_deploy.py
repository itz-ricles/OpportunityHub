def test_health_ok(client):
    res = client.get("/health")
    assert res.status_code == 200 and res.get_json() == {"status": "ok"}


def test_health_reports_503_when_database_is_down(client, monkeypatch):
    def boom():
        raise RuntimeError("db down")
    monkeypatch.setattr(routes_public, "get_db", boom)
    res = client.get("/health")
    assert res.status_code == 503 and res.get_json() == {"status": "unavailable"}
    assert b"db down" not in res.data                       # no internal details leaked


def test_missing_flask_env_means_production(monkeypatch, tmp_path):
    monkeypatch.delenv("FLASK_ENV", raising=False)
    app = create_app(test_config={"SECRET_KEY": "k" * 48, "DATABASE_URL": None,
                                  "DATABASE_PATH": str(tmp_path / "x.db")})
    assert app.debug is False and app.testing is False
    assert app.config["SESSION_COOKIE_SECURE"] is True


def test_force_https_switch(monkeypatch):
    monkeypatch.setenv("FORCE_HTTPS", "false")
    importlib.reload(config)
    assert config.ProductionConfig.SESSION_COOKIE_SECURE is False
    monkeypatch.delenv("FORCE_HTTPS")
    importlib.reload(config)
    assert config.ProductionConfig.SESSION_COOKIE_SECURE is True


def test_no_hsts_when_https_not_enforced(tmp_path):
    app = create_app("production", {"SECRET_KEY": "k" * 48, "DATABASE_URL": None,
                                    "DATABASE_PATH": str(tmp_path / "h.db"), "SESSION_COOKIE_SECURE": False})
    assert "Strict-Transport-Security" not in app.test_client().get("/health").headers


def _bad_login(client, forwarded_ip):
    return client.post("/login", data={"email": "x@example.com", "password": "bad-password"},
                       headers={"X-Forwarded-For": forwarded_ip})


def test_spoofed_forwarded_header_ignored_without_trusted_proxy(client):
    codes = [_bad_login(client, f"10.1.1.{i}").status_code for i in range(6)]
    assert codes == [401] * 5 + [429]                       # rotating fake IPs does not dodge the limiter


def test_trusted_proxy_uses_real_client_ip(tmp_path):
    app = create_app("testing", {"DATABASE_PATH": str(tmp_path / "p.db"), "PROXY_COUNT": 1})
    from db import init_db
    with app.app_context():
        init_db()
    client = app.test_client()
    assert [_bad_login(client, f"10.1.1.{i}").status_code for i in range(6)] == [401] * 6   # different users
    assert [_bad_login(client, "10.9.9.9").status_code for _ in range(6)][-1] == 429         # same user


def test_failed_login_is_logged_without_secrets(client, caplog):
    caplog.set_level(logging.INFO)
    client.post("/login", data={"email": "someone@example.com", "password": "super-secret-pw"})
    assert "Failed login attempt" in caplog.text
    assert "super-secret-pw" not in caplog.text and "someone@example.com" not in caplog.text


def test_admin_actions_are_audit_logged(admin, caplog):
    caplog.set_level(logging.INFO)
    admin.post("/admin/opportunities/new", data=NEW)
    admin.post("/admin/opportunities/1/deactivate")
    admin.post("/admin/opportunities/1/delete")
    for action in ("action=create", "action=inactive", "action=delete"):
        assert action in caplog.text


def test_row_supports_name_index_and_dict():
    r = Row(a=1, b=2)
    assert r["b"] == 2 and r[0] == 1 and dict(r) == {"a": 1, "b": 2}


def test_postgres_placeholder_translation():
    pg = Database(None, "postgres")
    assert pg._sql("SELECT * FROM t WHERE a = ? AND b LIKE '%x'") == "SELECT * FROM t WHERE a = %s AND b LIKE '%%x'"
    assert Database(None, "sqlite")._sql("a = ?") == "a = ?"
    assert pg.like == "ILIKE" and Database(None, "sqlite").like == "LIKE"


def test_postgres_schema_conversion():
    from db import postgres_schema
